// ── Як їдуть по полю ──────────────────────────────────────────────────────
//
// Програма відповідає «на 3-му проході глушити 14–17». Але «прохід 3» вона
// рахує від краю поля, а механізатор рахує свої заїзди — і це різні числа,
// щойно він їде не підряд.
//
// А не підряд їздять постійно. Човниковий хід із грушоподібним розворотом —
// основний спосіб на сівбі, і він справді йде сусідніми смугами. Але коли
// радіус повороту більший за захват (широкий агрегат, важкий трактор), петлю
// робити нема де: тоді йдуть через одну смугу, а на зворотному шляху
// закривають пропущені. На великих полях те саме роблять загінками — поле
// ділять на смуги по кілька проходів і закривають кожну окремо.
//
// Геометрія від цього не міняється: ті самі смуги лягають у ті самі місця,
// і колія нарізається та сама. Міняється лише те, яким числом назвати прохід
// у кабіні — і з якого боку в цей момент сівалка. Саме тому напрямок «туди
// чи назад» рахується від номера заїзду, а не від місця смуги: на ході через
// одну другий заїзд — це п'ята смуга, і сівалка на ній розвернена.

// Способи руху. Назви ті, якими їх звуть у полі, а не в підручнику.
export const DRIVE_MODES = [
  {
    key: 'row',
    label: 'Підряд, сусідніми смугами',
    hint: 'Човниковий хід із грушоподібним розворотом — основний спосіб на сівбі.',
  },
  {
    key: 'skip',
    label: 'Через одну смугу',
    hint: 'Коли петлю робити нема де: йдуть через смугу, а назад закривають пропущені. '
      + 'Розворот виходить без петлі й коротший.',
  },
  {
    key: 'lands',
    label: 'Загінками',
    hint: 'Поле ділять на загінки по кілька проходів і закривають кожну окремо — '
      + 'так менше холостих переїздів на довгому полі.',
  },
]

export const driveMode = (key) => DRIVE_MODES.find((m) => m.key === key) || DRIVE_MODES[0]

// Порядок заїздів: на якому місці поля механізатор опиниться на n-му заїзді.
// Повертає масив позицій (0-based) у порядку руху.
//
// Через одну: туди кожною другою смугою, назад — пропущеними, у зворотному
// порядку. Саме так і їдуть: доїхав до краю й повертаєшся, закриваючи
// пропуски, а не женеш через усе поле назад до початку.
export function passOrder(count, { mode = 'row', land = 0 } = {}) {
  const n = Math.max(0, Math.floor(Number(count)) || 0)
  if (n === 0) return []
  const key = driveMode(mode).key
  if (key === 'row') return Array.from({ length: n }, (_, i) => i)

  const skip = (from, to) => {           // [from, to) через одну, назад пропущеними
    const up = []
    const back = []
    for (let i = from; i < to; i++) (((i - from) % 2) ? back : up).push(i)
    return [...up, ...back.reverse()]
  }

  if (key === 'skip') return skip(0, n)

  // Загінками: усередині кожної йдуть так само через одну. Ширина загінки в
  // проходах приходить з форми; нуль чи сміття означає «на весь гін».
  const size = Math.max(2, Math.floor(Number(land)) || 0)
  const out = []
  for (let from = 0; from < n; from += size) out.push(...skip(from, Math.min(from + size, n)))
  return out
}

// ── Поворотна смуга ───────────────────────────────────────────────────────
//
// Її не вгадують, а рахують, і правило просте: обсів має бути цілим числом
// проходів сівалки — інакше остання смуга обсіву ляже не там, де її чекають.
// Скільки саме проходів, вирішує розворот: з петлею агрегат виписує грушу й
// потребує чотирьох проходів, без петлі — трьох. Багатосівалковому агрегату
// вистачає на прохід менше: він ширший, і та сама петля займає меншу частку
// його захвату.
export const TURN_KINDS = [
  { key: 'loop', label: 'З петлею (грушоподібний)', passes: 4, wide: 3 },
  { key: 'free', label: 'Без петлі', passes: 3, wide: 2 },
]

export const turnKind = (key) => TURN_KINDS.find((t) => t.key === key) || TURN_KINDS[0]

// Скільки метрів обсіву брати під цей агрегат і цей розворот.
export function headlandFor({ step, turn = 'loop', wide = false }) {
  const s = Number(step)
  if (!Number.isFinite(s) || !(s > 0)) return null
  const kind = turnKind(turn)
  const passes = wide ? kind.wide : kind.passes
  return { passes, width: Math.round(passes * s * 1000) / 1000, turn: kind.key, label: kind.label }
}
